# OBJ encoding


def obj_to_base64(vertices: np.ndarray, faces: np.ndarray) -> str:
    """Encode a mesh as a base64 OBJ string for the Modal endpoint."""
    buf = io.StringIO()
    buf.write("# Generated by ml/shapeopt/gen_shapes.py\n")
    for v in vertices:
        buf.write(f"v {v[0]:.8f} {v[1]:.8f} {v[2]:.8f}\n")
    for face in faces:
        buf.write(f"f {face[0] + 1} {face[1] + 1} {face[2] + 1}\n")
    return base64.b64encode(buf.getvalue().encode("utf-8")).decode("ascii")


# Modal submission with async polling


def submit_job(endpoint: str, payload: dict, timeout: int = 30) -> str | None:
    """POST to the render endpoint. Returns a job_id on success, None on error."""
    try:
        resp = requests.post(endpoint, json=payload, timeout=timeout)
        resp.raise_for_status()
        data = resp.json()
        if data.get("status") == "accepted":
            return data["job_id"]
        # Some endpoints return the result directly (synchronous mode)
        if data.get("status") == "complete":
            return data
        print(f"  Unexpected response: {data}", file=sys.stderr)
        return None
    except Exception as e:
        print(f"  Submit failed: {e}", file=sys.stderr)
        return None


def poll_job(
    endpoint: str, job_id: str, poll_interval: float = 5.0, timeout: float = 1800.0
) -> dict | None:
    """
    Poll the job_status endpoint until the job finishes or times out.

    The status endpoint is derived from the render endpoint by replacing
    the trailing path component. For example:
        render:  https://x.modal.run/render_endpoint
        status:  https://x.modal.run/job_status?job_id=...
    """
    # Build the status URL from the render endpoint
    base = endpoint.rsplit("/", 1)[0]
    status_url = f"{base}/job_status"

    t0 = time.monotonic()
    while time.monotonic() - t0 < timeout:
        try:
            resp = requests.get(status_url, params={"job_id": job_id}, timeout=30)
            resp.raise_for_status()
            data = resp.json()

            status = data.get("status")
            if status == "complete":
                return data
            if status == "error":
                return data
            # Still rendering, keep waiting
        except requests.RequestException as e:
            print(f"  Poll error (will retry): {e}", file=sys.stderr)

        time.sleep(poll_interval)

    return {"status": "error", "error": f"Timed out after {timeout}s"}


def run_simulation(endpoint: str, payload: dict) -> dict:
    """Submit a job and poll for results. Returns the result dict."""
    result = submit_job(endpoint, payload)

    # submit_job returned a full result dict (synchronous endpoint)
    if isinstance(result, dict):
        return result

    if result is None:
        return {"status": "error", "error": "Failed to submit job"}

    job_id = result
    poll_result = poll_job(endpoint, job_id)
    if poll_result is None:
        return {"status": "error", "error": "Polling returned None"}
    return poll_result


# Sample tracking


def sample_id(model: str, idx: int) -> str:
    key = f"shapeopt_{model}_{idx}"
    return hashlib.md5(key.encode()).hexdigest()[:12]


def load_completed_samples() -> set[str]:
    if not MANIFEST_FILE.exists():
        return set()
    completed = set()
    with MANIFEST_FILE.open() as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("status") == "complete":
                completed.add(row["sample_id"])
    return completed


def save_manifest_row(
    sid: str,
    model: str,
    idx: int,
    status: str,
    cd: float | None,
    cl: float | None,
    error: str | None = None,
) -> None:
    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    write_header = not MANIFEST_FILE.exists()
    with MANIFEST_FILE.open("a", newline="") as f:
        writer = csv.writer(f)
        if write_header:
            writer.writerow(
                [
                    "sample_id",
                    "model",
                    "sample_idx",
                    "status",
                    "cd_value",
                    "cl_value",
                    "error",
                ]
            )
        writer.writerow(
            [
                sid,
                model,
                idx,
                status,
                f"{cd:.6f}" if cd is not None else "",
                f"{cl:.6f}" if cl is not None else "",
                error or "",
            ]
        )


def save_results_row(
    sid: str, model: str, idx: int, displacements: np.ndarray, cd: float, cl: float
) -> None:
    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    write_header = not RESULTS_FILE.exists()
    with RESULTS_FILE.open("a", newline="") as f:
        writer = csv.writer(f)
        if write_header:
            writer.writerow(
                [
                    "sample_id",
                    "model",
                    "sample_idx",
                    "cd_value",
                    "cl_value",
                    "displacements",
                ]
            )
        writer.writerow(
            [
                sid,
                model,
                idx,
                f"{cd:.6f}",
                f"{cl:.6f}",
                json.dumps(displacements.tolist()),
            ]
        )


# Binary export (.sobin)


def export_sobin(results_file: Path, output_file: Path) -> int:
    """
    Convert CSV results to .sobin binary format.

    Header (20 bytes):
        uint32 magic = 0x534F5054
        uint32 version = 1
        uint32 num_samples
        uint32 num_ffd_params
        uint32 num_outputs = 2

    Per sample:
        float32[num_ffd_params] ffd_displacements
        float32[2] [cd, cl]
    """
    if not results_file.exists():
        print("No results file found, skipping binary export.")
        return 0

    records = []
    with results_file.open() as f:
        reader = csv.DictReader(f)
        for row in reader:
            if not row["cd_value"] or not row["cl_value"]:
                continue
            disps = np.array(json.loads(row["displacements"]), dtype=np.float32)
            cd = float(row["cd_value"])
            cl = float(row["cl_value"])
            records.append((disps, cd, cl))

    if not records:
        print("No valid records found.")
        return 0

    num_ffd_params = len(records[0][0])
    # Verify all records have the same parameter count
    for i, (d, _, _) in enumerate(records):
        if len(d) != num_ffd_params:
            print(
                f"WARNING: Sample {i} has {len(d)} params, expected {num_ffd_params}. Skipping.",
                file=sys.stderr,
            )
    records = [r for r in records if len(r[0]) == num_ffd_params]

    output_file.parent.mkdir(parents=True, exist_ok=True)
    with output_file.open("wb") as f:
        f.write(struct.pack("<I", SOBIN_MAGIC))
        f.write(struct.pack("<I", SOBIN_VERSION))
        f.write(struct.pack("<I", len(records)))
        f.write(struct.pack("<I", num_ffd_params))
        f.write(struct.pack("<I", 2))  # num_outputs (cd, cl)

        for disps, cd, cl in records:
            f.write(disps.astype(np.float32).tobytes())
            f.write(struct.pack("<ff", cd, cl))

    size_kb = output_file.stat().st_size / 1024
    print(f"Exported {len(records)} samples to {output_file} ({size_kb:.1f} KB)")
    print(f"  FFD params per sample: {num_ffd_params}")
    return len(records)


# Main pipeline


def run_sweep(
    config_path: str, endpoint: str, resume: bool = False, seed: int | None = None
) -> None:
    config = load_config(config_path)
    if seed is None:
        seed = config.get("seed")

    base_models = config["base_models"]
    n_control = tuple(config["ffd_grid"])
    num_samples = config["num_samples"]
    max_fraction = config["displacement_range"]
    symmetric = config.get("enforce_symmetry", True)
    wind_speed = config["wind_speed"]
    reynolds = config["reynolds"]
    duration = config["duration"]
    collision_mode = config.get("collision_mode", 2)
    retry_limit = config.get("retry_limit", 3)

    completed = load_completed_samples() if resume else set()

    for model in base_models:
        obj_path = MODEL_OBJ_PATHS.get(model)
        if obj_path is None or not obj_path.exists():
            print(f"ERROR: OBJ not found for model '{model}' at {obj_path}", file=sys.stderr)
            continue

        print(f"\n{'=' * 60}")
        print(f"Model: {model}")
        print(f"OBJ: {obj_path}")
        print(f"{'=' * 60}")

        vertices, faces = load_obj(str(obj_path))
        bbox_min, bbox_max = compute_bbox(vertices)
        lattice = FFDLattice(bbox_min, bbox_max, n_control=n_control)

        num_params = lattice.get_num_params()
        print(f"  Vertices: {len(vertices)}")
        print(f"  FFD grid: {n_control}, total params: {num_params}")
        print(f"  Samples to generate: {num_samples + 1} (baseline + {num_samples} deformed)")

        # Generate LHS samples
        print(f"  Generating {num_samples} LHS samples...")
        lhs_samples = lattice.sample_random(
            num_samples,
            max_fraction=max_fraction,
            symmetric=symmetric,
            rng=np.random.default_rng(seed),
        )

        # Prepend the baseline (zero displacements) as sample 0
        baseline = np.zeros((1, num_params), dtype=np.float64)
        all_samples = np.vstack([baseline, lhs_samples])

        success = 0
        failed = 0

        for idx in range(len(all_samples)):
            sid = sample_id(model, idx)

            if sid in completed:
                success += 1
                continue

            displacements = all_samples[idx]
            tag = "baseline" if idx == 0 else f"sample {idx}/{num_samples}"

            # Deform the mesh
            deformed = lattice.deform(vertices, displacements)

            # Encode as base64 OBJ
            obj_b64 = obj_to_base64(deformed, faces)

            payload = {
                "job_id": f"shapeopt_{model}_{idx}",
                "wind_speed": wind_speed,
                "reynolds": reynolds,
                "duration": duration,
                "collision_mode": collision_mode,
                "model": "custom",
                "obj_data": obj_b64,
                "viz_mode": 1,
            }

            # Submit with retries
            result = None
            for attempt in range(retry_limit):
                result = run_simulation(endpoint, payload)
                if result.get("status") == "complete":
                    break
                if attempt < retry_limit - 1:
                    print(f"    Retry {attempt + 1} for {tag}...")
                    time.sleep(2.0)

            cd = result.get("cd_value") if result else None
            cl = result.get("cl_value") if result else None
            status = result.get("status", "error") if result else "error"
            error = result.get("error") if result else "submit failed"

            if status == "complete" and cd is not None:
                save_manifest_row(sid, model, idx, "complete", cd, cl)
                save_results_row(sid, model, idx, displacements.astype(np.float32), cd, cl)
                success += 1
                print(
                    f"  [{success + failed}/{len(all_samples)}] {tag} -> Cd={cd:.4f}, Cl={cl:.4f}"
                )
            else:
                save_manifest_row(sid, model, idx, "error", None, None, error=str(error))
                failed += 1
                print(f"  [{success + failed}/{len(all_samples)}] {tag} -> FAILED: {error}")

        print(f"\n  {model}: {success} complete, {failed} failed")

    # Export binary
    n_exported = export_sobin(RESULTS_FILE, SOBIN_FILE)
    if n_exported:
        compute_stats()


def sample_displacements(lattice: FFDLattice, config: dict, seed: int | None) -> np.ndarray:
    """Baseline (zero displacements) followed by the LHS samples"""
    lhs = lattice.sample_random(
        config["num_samples"],
        max_fraction=config["displacement_range"],
        symmetric=config.get("enforce_symmetry", True),
        rng=np.random.default_rng(seed),
    )
    return np.vstack([np.zeros((1, lattice.get_num_params())), lhs])


def read_case(row: dict) -> dict:
    """Cd, its interval, Cl and the frontal area of one study row"""
    manifest = json.loads(Path(row["manifest"]).read_text())
    return {
        "cd": row["cd"],
        "cd_ci95": row["cd_ci95"],
        "cl": (manifest.get("results") or {}).get("cl_mean"),
        "ref_area": (manifest.get("model") or {}).get("ref_area"),
        "reynolds": row["reynolds"],
        "tau": row["tau"],
    }


LOCAL_COLUMNS = [
    "sample_id",
    "model",
    "sample_idx",
    "status",
    "cd_value",
    "cl_value",
    "cd_ci95",
    "ref_area",
    "reynolds",
    "tau",
    "frontal_area_ratio",
    "volume_ratio",
    "error",
    "displacements",
]


def run_local(
    config_path: str,
    binary: Path,
    out: Path,
    workdir: Path = PROJECT_ROOT / "simulation",
    seed: int | None = None,
    timeout: float | None = None,
    backend=None,
) -> int:
    """Run every sample through the study runner, then export the dataset"""
    import study

    config = load_config(config_path)
    if seed is None:
        seed = config.get("seed")
    if len(config["base_models"]) != 1:
        raise ConfigError(
            config_path, ["base_models: the surrogate has no model input, give one base model"]
        )
    if "grid" not in config:
        raise ConfigError(config_path, ["grid: --local needs a grid"])
    model = config["base_models"][0]
    obj_path = MODEL_OBJ_PATHS[model]
    vertices, faces = load_obj(str(obj_path))
    lattice = FFDLattice(*compute_bbox(vertices), n_control=tuple(config["ffd_grid"]))
    ref = protocol.reference(vertices, float(config["reynolds"]))
    run = {"grid": config["grid"], **protocol.run_settings(duration=int(config["duration"]))}

    samples = sample_displacements(lattice, config, seed)
    mesh_dir = out / "meshes"
    mesh_dir.mkdir(parents=True, exist_ok=True)
    rows, cases = [], []
    for idx, disp in enumerate(samples):
        deformed = lattice.deform(vertices, disp)
        geo = mesh_checks.check(vertices, deformed, faces, lattice, disp)
        row = {
            "sample_id": sample_id(model, idx),
            "model": model,
            "sample_idx": idx,
            "frontal_area_ratio": geo["frontal_area_ratio"],
            "volume_ratio": geo["volume_ratio"],
            "displacements": json.dumps(disp.astype(np.float32).tolist()),
        }
        if not geo["ok"]:
            row.update(status="rejected", error="; ".join(geo["problems"]))
            rows.append(row)
            continue
        path = mesh_dir / f"{model}_{idx:04d}.obj"
        save_obj(path, deformed, faces)
        params = protocol.case_params(path, deformed, ref, **run)
        rows.append(row | {"case": study.case_name(params)})
        cases.append(params)

    study_file = protocol.write_study(
        out / "study.yaml", binary, workdir, out / "runs", cases, f"shapes_{model}", timeout
    )
    loaded = study.load_study(study_file)
    result, _ = study.run_study(loaded, backend or study.LocalBackend())
    by_name = {r["name"]: r for r in result["rows"]}
    for row in rows:
        case = by_name.get(row.pop("case", None))
        if case is None:
            continue
        if case["status"] != "ok" or case["cd"] is None:
            row.update(status="error", error=case["error"] or "no Cd")
            continue
        got = read_case(case)
        row.update(status="complete", cd_value=got.pop("cd"), cl_value=got.pop("cl"), **got)

    results = out / "results.csv"
    with results.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=LOCAL_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(
            {k: ("" if row.get(k) is None else row.get(k)) for k in LOCAL_COLUMNS} for row in rows
        )
    meta = {
        "base_model": model,
        "base_obj": str(obj_path),
        "grid": config["grid"],
        "run": {k: v for k, v in run.items() if k != "grid"},
        "reference": ref.to_dict(),
        "ffd_grid": list(config["ffd_grid"]),
        "displacement_range": config["displacement_range"],
        "enforce_symmetry": config.get("enforce_symmetry", True),
        "seed": seed,
        "wind_speed": config["wind_speed"],
        "args": ["--strict-reynolds"],
    }
    (out / "protocol.json").write_text(json.dumps(meta, indent=2) + "\n")
    done = sum(r.get("status") == "complete" for r in rows)
    print(f"{done} of {len(rows)} samples complete, see {results}")
    for warning in result["warnings"]:
        print(f"WARNING: {warning}")
    return export_sobin(results, out / "shapeopt_data.sobin")


def compute_stats() -> dict | None:
    """Generate summary statistics."""
    if not MANIFEST_FILE.exists():
        return

    stats = {"total": 0, "complete": 0, "failed": 0, "by_model": {}}
    with MANIFEST_FILE.open() as f:
        reader = csv.DictReader(f)
        for row in reader:
            stats["total"] += 1
            if row["status"] == "complete":
                stats["complete"] += 1
            else:
                stats["failed"] += 1

            model = row["model"]
            if model not in stats["by_model"]:
                stats["by_model"][model] = {"count": 0, "cd_values": []}
            stats["by_model"][model]["count"] += 1
            if row["cd_value"]:
                stats["by_model"][model]["cd_values"].append(float(row["cd_value"]))

    for model_stats in stats["by_model"].values():
        cd_vals = model_stats.pop("cd_values")
        if cd_vals:
            model_stats["cd_mean"] = sum(cd_vals) / len(cd_vals)
            model_stats["cd_min"] = min(cd_vals)
            model_stats["cd_max"] = max(cd_vals)
            mean = model_stats["cd_mean"]
            model_stats["cd_std"] = (sum((x - mean) ** 2 for x in cd_vals) / len(cd_vals)) ** 0.5

    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    with STATS_FILE.open("w") as f:
        json.dump(stats, f, indent=2)

    print(f"\nStats: {stats['complete']} complete, {stats['failed']} failed")
    for model, ms in stats["by_model"].items():
        if "cd_mean" in ms:
            print(
                f"  {model}: {ms['count']} samples, "
                f"Cd mean={ms['cd_mean']:.4f} std={ms['cd_std']:.4f}"
            )

    return stats


def show_status() -> None:
    stats = compute_stats()
    if not stats:
        print("No data generated yet.")
        return

    print(f"Total samples: {stats['total']}")
    print(f"  Complete: {stats['complete']}")
    print(f"  Failed: {stats['failed']}")
    for model, ms in stats["by_model"].items():
        print(f"  {model}: {ms['count']} samples", end="")
        if "cd_mean" in ms:
            print(f", Cd mean={ms['cd_mean']:.4f} std={ms['cd_std']:.4f}")
        else:
            print()

    if SOBIN_FILE.exists():
        size_kb = SOBIN_FILE.stat().st_size / 1024
        print(f"\n  Binary: {SOBIN_FILE} ({size_kb:.1f} KB)")


# CLI


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate FFD shape optimization training data")
    parser.add_argument(
        "--config",
        default="shapeopt_config.yaml",
        help="Config YAML file (default: shapeopt_config.yaml)",
    )
    parser.add_argument(
        "--endpoint",
        default=None,
        help="Modal render endpoint URL",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Skip already-completed samples",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Seed for the LHS samples (default: seed in config, else random)",
    )
    parser.add_argument(
        "--status",
        action="store_true",
        help="Show data generation progress",
    )
    parser.add_argument(
        "--export-only",
        action="store_true",
        help="Re-export .sobin from existing CSV results",
    )
    parser.add_argument(
        "--local", action="store_true", help="run the solver here through the study runner"
    )
    parser.add_argument("--binary", type=Path, help="--local: solver binary")
    parser.add_argument("--out", type=Path, help="--local: output directory")
    parser.add_argument(
        "--workdir",
        type=Path,
        default=PROJECT_ROOT / "simulation",
        help="--local: directory the solver runs from (default: simulation/)",
    )
    parser.add_argument("--timeout", type=float, help="--local: seconds per case")
    args = parser.parse_args()

    if args.status:
        show_status()
        return

    if args.export_only:
        export_sobin(RESULTS_FILE, SOBIN_FILE)
        compute_stats()
        return

    if args.local:
        if not args.binary or not args.out:
            sys.exit("Error: --local needs --binary and --out")
        if not args.binary.is_file():
            sys.exit(f"Error: no solver binary at {args.binary}")
        config_path = SHAPEOPT_DIR / args.config
        n = run_local(
            str(config_path), args.binary, args.out, args.workdir, args.seed, args.timeout
        )
        sys.exit(0 if n else 1)

    endpoint = args.endpoint
    if not endpoint:
        import os

        endpoint = os.environ.get("MODAL_RENDER_ENDPOINT")
    if not endpoint:
        print(
            "Error: provide --endpoint or set MODAL_RENDER_ENDPOINT",
            file=sys.stderr,
        )
        sys.exit(1)

    config_path = SHAPEOPT_DIR / args.config
    if not config_path.exists():
        print(f"Error: config not found at {config_path}", file=sys.stderr)
        sys.exit(1)

    run_sweep(str(config_path), endpoint, resume=args.resume, seed=args.seed)


if __name__ == "__main__":
    try:
        main()
    except ConfigError as e:
        sys.exit(str(e))
